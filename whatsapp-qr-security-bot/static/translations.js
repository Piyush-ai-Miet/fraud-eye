// Text-to-Speech function for Hindi voice alerts
function speakAlert(message, lang = 'hi') {
    if ('speechSynthesis' in window) {
        const utterance = new SpeechSynthesisUtterance(message);
        utterance.lang = lang === 'hi' ? 'hi-IN' : 'en-US';
        utterance.rate = 0.9;
        utterance.pitch = 1;
        window.speechSynthesis.speak(utterance);
    }
}

// Get explanation for warning
function getExplanation(warning, lang = 'hi') {
    const explanations = translations[lang].explanations;
    
    if (warning.includes('HTTPS') || warning.includes('🔓')) {
        return explanations.noHTTPS;
    }
    if (warning.includes('IP address') || warning.includes('🌐')) {
        return explanations.ipAddress;
    }
    if (warning.includes('.tk') || warning.includes('.ml') || warning.includes('Suspicious domain')) {
        return explanations.freeDomain;
    }
    if (warning.includes('Scam keywords') || warning.includes('Phishing')) {
        return explanations.phishingKeywords;
    }
    if (warning.includes('SQL')) {
        return explanations.sqlInjection;
    }
    if (warning.includes('XSS')) {
        return explanations.xssAttack;
    }
    if (warning.includes('Short domain')) {
        return explanations.shortDomain;
    }
    if (warning.includes('days old')) {
        return explanations.newDomain;
    }
    
    return '';
}
